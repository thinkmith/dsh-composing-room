/**
 * Build the double-click installer (SFX) without any archiver dependency.
 *
 * IExpress ships with Windows and flattens its file list, so the payload is a
 * single self-contained PowerShell script plus a cmd wrapper: the plugin's
 * sources travel inside the script as base64, get written into the profile's
 * node_modules, and nothing else has to be unpacked next to it. Rebuild with
 *
 *   node build/build-sfx.mjs
 *
 * Outputs:
 *   dist/sfx/setup.ps1                     payload script (ASCII only)
 *   dist/sfx/install.cmd                   wrapper that runs it with -Bypass
 *   dist/sfx/iexpress.sed                  SED consumed by iexpress /N
 *   dist/dsh-composing-room-setup.exe      the double-clickable result
 */
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outDir = path.join(root, 'dist', 'sfx')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))

const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8')
const b64 = (rel) => Buffer.from(read(rel), 'utf8').toString('base64')

const files = [
  ['lib/index.js', read('lib/index.js')],
  ['lib/client.js', read('lib/client.js')],
  ['assets/prompt.default.txt', read('assets/prompt.default.txt')],
  ['package.json', JSON.stringify(pkg, null, 2) + '\n'],
]

const embedded = files
  .map(([rel, text], i) => {
    const name = `PAYLOAD_${i}`
    return `$${name}_PATH = '${rel}'
$${name}_B64 = @'
${Buffer.from(text, 'utf8').toString('base64')}
'@`
  })
  .join('\n\n')

const writes = files
  .map((_, i) => {
    const target = `Join-Path $pkgDir '${files[i][0].replace(/\//g, '\\')}'`
    return `Write-Embedded $PAYLOAD_${i}_PATH $PAYLOAD_${i}_B64`
  })
  .join('\n')

const script = `# dsh-composing-room - self-contained installer (generated by build/build-sfx.mjs)
# ASCII only: PowerShell 5.1 reads BOM-less files as GBK.
param(
  [string]$Profile = 'desktop',
  [switch]$SkipPatch
)

$ErrorActionPreference = 'Stop'
$pkgName = 'dsh-composing-room'
$profileDir = Join-Path $env:USERPROFILE (".dsh\\profiles\\$Profile")
$targetDir = Join-Path $profileDir "node_modules\\$pkgName"
$patchFile = Join-Path $profileDir 'cordis.patch.yml'
$stateDir = Join-Path $env:USERPROFILE '.dsh\\composing-room'

if (-not (Test-Path $profileDir)) {
  Write-Host "profile not found: $profileDir"
  Write-Host 'start DeepSeek Harness once so the profile exists, then run this again.'
  exit 2
}

$pkgDir = $targetDir
function Write-Embedded([string]$rel, [string]$data) {
  $dest = Join-Path $pkgDir ($rel -replace '/', '\\')
  $parent = Split-Path -Parent $dest
  if (-not (Test-Path $parent)) { New-Item -ItemType Directory -Force -Path $parent | Out-Null }
  $bytes = [Convert]::FromBase64String(($data -replace "\\s", ''))
  [System.IO.File]::WriteAllBytes($dest, $bytes)
}

${embedded}

if (Test-Path $targetDir) {
  Write-Host "updating existing install: $targetDir"
} else {
  New-Item -ItemType Directory -Force -Path $targetDir | Out-Null
  Write-Host "installed to: $targetDir"
}

${writes}

if ($SkipPatch) {
  Write-Host 'patch skipped (add the insert block by hand)'
} else {
  $existing = if (Test-Path $patchFile) { Get-Content $patchFile -Raw } else { '' }
  if ($null -eq $existing) { $existing = '' }
  if ($existing -match '(?m)^\\s*-\\s*id:\\s*composing-room\\s*$') {
    Write-Host 'patch already declares composing-room'
  } else {
    $block = @"
# --- composing room (local plugin: manual system-section injection) ---
# Disarmed by default. /room on | /room off | /room reload  (state lives in
# %USERPROFILE%\\.dsh\\composing-room\\state.json, text in prompt.txt beside it).
- insert:
    - id: composing-room
      name: '$pkgName'
"@
    $sep = if ($existing.Length -gt 0 -and -not $existing.EndsWith("\`n")) { "\`n" } else { '' }
    Add-Content -Path $patchFile -Value ($sep + $block) -Encoding UTF8
    Write-Host "patched: $patchFile"
  }
}

if (-not (Test-Path $stateDir)) { New-Item -ItemType Directory -Force -Path $stateDir | Out-Null }
$prompt = Join-Path $stateDir 'prompt.txt'
if (-not (Test-Path $prompt)) {
  Copy-Item -Path (Join-Path $targetDir 'assets\\prompt.default.txt') -Destination $prompt -Force
  Write-Host "seeded payload: $prompt"
}
$state = Join-Path $stateDir 'state.json'
if (-not (Test-Path $state)) {
  $obj = [ordered]@{ armed = $false; order = 12000; textPath = $prompt }
  Set-Content -Path $state -Value ($obj | ConvertTo-Json) -Encoding UTF8
  Write-Host "seeded state: $state"
}

Write-Host ''
Write-Host 'done. restart DeepSeek Harness once, then look right of the composer:'
Write-Host '  a pill labelled "PAIBAN off" -- click it, it turns green, the section is live.'
Write-Host '  /room on | /room off | /room reload also work in chat.'
`

fs.mkdirSync(outDir, { recursive: true })
const setupPath = path.join(outDir, 'setup.ps1')
fs.writeFileSync(setupPath, script, { encoding: 'utf8' })
if (fs.readFileSync(setupPath, 'utf8').match(/[^\x00-\x7F]/)) {
  throw new Error('setup.ps1 must stay ASCII: check the template for non-ASCII characters')
}

const cmd = [
  '@echo off',
  'rem Double-click installer for dsh-composing-room (generated).',
  'setlocal',
  'cd /d "%~dp0"',
  'echo.',
  'echo   dsh-composing-room installer',
  'echo   -----------------------------',
  'echo.',
  'powershell -NoProfile -ExecutionPolicy Bypass -File "%~dp0setup.ps1" %*',
  'set RC=%ERRORLEVEL%',
  'echo.',
  'if "%RC%"=="0" (',
  '  echo   Finished. Restart DeepSeek Harness once, then click the pill',
  '  echo   next to the composer to arm the section.',
  ') else (',
  '  echo   Installer exited with code %RC%. Scroll up for the reason.',
  ')',
  'echo.',
  'pause',
  'endlocal',
  '',
].join('\r\n')
fs.writeFileSync(path.join(outDir, 'install.cmd'), cmd, { encoding: 'ascii' })

const exeName = `dsh-composing-room-${pkg.version}-setup.exe`
const finalExe = path.join(root, 'dist', exeName)

// IExpress chokes on spaces in TargetName/SourceFiles paths, and this repo lives
// under "D:\deepseek harness", so stage the payload in a space-free directory.
const stage = path.join(process.env.SystemDrive ?? 'C:', '\\Temp\\iex-stage')
fs.rmSync(stage, { recursive: true, force: true })
fs.mkdirSync(stage, { recursive: true })
fs.copyFileSync(setupPath, path.join(stage, 'setup.ps1'))
fs.copyFileSync(path.join(outDir, 'install.cmd'), path.join(stage, 'install.cmd'))
const stagedExe = path.join(stage, 'setup.exe')

const sed = [
  '[Version]',
  'Class=IEXPRESS',
  'SEDVersion=3',
  '[Options]',
  'PackagePurpose=InstallApp',
  'ShowInstallProgramWindow=1',
  'HideExtractAnimation=0',
  'UseLongFileName=1',
  'InsideCompressed=0',
  'CAB_FixedSize=0',
  'CAB_ResvCodeSigning=0',
  'RebootMode=N',
  'InstallPrompt=%InstallPrompt%',
  'DisplayLicense=%DisplayLicense%',
  'FinishMessage=%FinishMessage%',
  'TargetName=%TargetName%',
  'FriendlyName=%FriendlyName%',
  'AppLaunched=%AppLaunched%',
  'PostInstallCmd=%PostInstallCmd%',
  'AdminQuietInstCmd=%AdminQuietInstCmd%',
  'UserQuietInstCmd=%UserQuietInstCmd%',
  'SourceFiles=SourceFiles',
  '',
  '[Strings]',
  'InstallPrompt=',
  'DisplayLicense=',
  'FinishMessage=',
  `TargetName=${stagedExe}`,
  'FriendlyName=composing room installer',
  'AppLaunched=install.cmd',
  'PostInstallCmd=<None>',
  'AdminQuietInstCmd=',
  'UserQuietInstCmd=',
  'FILE0="install.cmd"',
  'FILE1="setup.ps1"',
  '',
  '[SourceFiles]',
  'SourceFiles0=' + stage + '\\',
  '[SourceFiles0]',
  '%FILE0%=',
  '%FILE1%=',
  '',
].join('\r\n')

const sedPath = path.join(stage, 'build.sed')
fs.writeFileSync(sedPath, sed, { encoding: 'ascii' })
fs.copyFileSync(sedPath, path.join(outDir, 'iexpress.sed'))

execFileSync(path.join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'iexpress.exe'), ['/N', '/Q', sedPath], {
  cwd: stage,
  stdio: 'inherit',
})

if (!fs.existsSync(stagedExe)) throw new Error('iexpress did not produce the exe')
fs.copyFileSync(stagedExe, finalExe)
const size = fs.statSync(finalExe).size
console.log(`setup.ps1  ${fs.statSync(setupPath).size} bytes`)
console.log(`installer  ${finalExe}  ${size} bytes`)
